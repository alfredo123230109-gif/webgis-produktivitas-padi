    function hitungMetrikRegresi(pts, keyIndex) {
        const x = pts.map(p => p[keyIndex]);
        const y = pts.map(p => p.prod);
        const n = x.length;
        if (n === 0) return { r2: "-", rmse: "-", mae: "-" };

        let sumX = 0, sumY = 0, sumXY = 0, sumX2 = 0;
        for (let i = 0; i < n; i++) {
            sumX += x[i]; sumY += y[i]; sumXY += x[i] * y[i]; sumX2 += x[i] * x[i];
        }
        const denom = (n * sumX2 - sumX * sumX);
        if (denom === 0) return { r2: "-", rmse: "-", mae: "-" };

        const slope = (n * sumXY - sumX * sumY) / denom;
        const intercept = (sumY - slope * sumX) / n;

        let ssRes = 0, ssTot = 0, absErrSum = 0;
        const meanY = sumY / n;
        for (let i = 0; i < n; i++) {
            const yPred = slope * x[i] + intercept;
            ssRes += Math.pow(y[i] - yPred, 2);
            ssTot += Math.pow(y[i] - meanY, 2);
            absErrSum += Math.abs(y[i] - yPred);
        }
        const r2 = ssTot !== 0 ? 1 - (ssRes / ssTot) : 0;
        const rmse = Math.sqrt(ssRes / n);
        const mae = absErrSum / n;

        return { r2: r2.toFixed(3), rmse: rmse.toFixed(3), mae: mae.toFixed(3) };
    }

